// Layer 1, data. Reads the three generated feed files into the counts and run dates the command
// center shows. Server side only: it reads the filesystem and no client module may import it.
//
// It summarises and does not carry. The Lit Watch, Position Leads and LinkedIn views read these
// files for themselves; what is here is the handful of numbers the Focus board needs, so that a
// board rebuild does not pull several thousand lines of feed entries over the socket.
//
// A file or folder that is not there is null for that feed and no finding when the hub's settings
// file does not name it: the feeds are generated by the hub's update tasks, so a hub that has
// never run one legitimately has none. A leads or radar file the hub's `collections:` list names
// and that is not there is the finding a named and missing registry is. A file that is there and
// does not parse is a finding, like every other broken file.

import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import {
    primaryKeyOf,
    type Feeds,
    type FeedFiles,
    type FeedKind,
    type Finding,
    type HubLayout,
    type Lead,
    type RawFeeds
} from '../../model/index.ts';
import { keyedSchema } from '../../snapshot/schema/field.ts';
import { ISO_DATE } from '../../helpers/dates.ts';
import { feedPrimaryKey } from '../../helpers/hub-names.ts';
// `str` here is the shared `text`: this file's reading of a missing or mistyped value has always
// been the empty string rather than undefined, and the alias keeps that reading at every call it
// makes. The lead's status is the one value it does not read for itself, since the rule that closes
// a lead reads it in data/accounts/leads.ts.
import { text as str } from '../../helpers/guards.ts';
import { itemsShape, mapShape, readOr, rowsShape } from '../../shapes/shapes.ts';
import { isLeadClosed } from '../../accounts/leads.ts';
import { identityFindings, leadStatusFindings } from '../../snapshot/validate.ts';
import { vocabKeys } from '../../shapes/vocab-keys.ts';
import { findingText, type TextCatalog } from '../../helpers/finding-text.ts';
import { errorLine, readYamlMap } from '../yaml-file.ts';

/**
 * The date a `meta.log` line of the leads feed records a run of the position scout on: the
 * line's leading date, when the line holds the hub's `leads_run_word` in any case after it. An
 * empty word records no run.
 */
function scoutRun(line: string, word: string): string | null {
    if (word === '') return null;
    const found = /^\s*(\d{4}-\d{2}-\d{2})\b/.exec(line);
    if (found === null) return null;
    return line.slice(found[0].length).toLowerCase().includes(word.toLowerCase()) ? found[1] : null;
}

/** A `date:` line of a LinkedIn post's front matter. */
const FRONT_DATE = /^date:\s*["']?(\d{4}-\d{2}-\d{2})/m;

/** The maps among the `entries:` of a feed file. */
const entriesShape = rowsShape(mapShape);

/** The `meta:` map of a feed file, and an empty map for a file that has none. */
function metaOf(data: Record<string, unknown>): Record<string, unknown> {
    return readOr(mapShape, data.meta, {});
}

/** One lead of the feed, with its `deadline:` when it is a day written YYYY-MM-DD. */
function lead(entry: Record<string, unknown>): Lead {
    const deadline = str(entry.deadline);
    const fit = str(entry.fit);
    return {
        title: str(entry.title),
        deadline: ISO_DATE.test(deadline) ? deadline : null,
        status: str(entry.status),
        fit: fit === '' ? null : fit
    };
}

/**
 * The leads file answers two of the five feeds: the live leads themselves, and the position scout's
 * own run date, which the file records as the leading date of a `meta.log` line rather than as a
 * run field of its own. It also reports the identity findings of every lead of the file and each
 * status that is no word of `lead_statuses:`, since the live leads alone carry no file and no
 * position the snapshot could check them by. `word` is the hub's `leads_run_word`; an empty word
 * gives no scout feed, since no line of the log can then record a run.
 */
function leads(
    file: string,
    catalog: TextCatalog,
    merged: Record<string, unknown>,
    word: string,
    findings: Finding[],
    named: boolean
): { leads: Feeds['leads']; scout: Feeds['scout'] } {
    const data = readYamlMap(file, catalog, findings, missing(catalog, named));
    if (data === null) return { leads: null, scout: null };
    const entries = readOr(entriesShape, data.entries, []);
    // Every lead of the file is checked for its primary key, the closed ones too, since a write
    // addresses a lead by it whether it is live or not. A file with no primary key is the schema
    // run's one finding.
    const listed = feedPrimaryKey(merged.collections, 'leads');
    const primaryKey = primaryKeyOf(keyedSchema(data.schema), listed);
    if (primaryKey !== null) findings.push(...identityFindings(file, primaryKey, entries, catalog));
    findings.push(...leadStatusFindings(file, entries, vocabKeys(merged.lead_statuses), catalog));
    const live = entries.filter((entry) => !isLeadClosed(merged, entry.status)).map(lead);
    const runs = readOr(itemsShape, metaOf(data).log, [])
        .map((line) => scoutRun(str(line), word))
        .filter((found): found is string => found !== null);
    const newest = runs.sort().at(-1);
    return { leads: live, scout: word === '' ? null : { lastRun: newest ?? null } };
}

/** The Lit Watch radar: the day the last sweep ran. */
function radar(
    file: string,
    catalog: TextCatalog,
    findings: Finding[],
    named: boolean
): Feeds['radar'] {
    const data = readYamlMap(file, catalog, findings, missing(catalog, named));
    if (data === null) return null;
    const run = str(metaOf(data).last_run);
    return { lastRun: run === '' ? null : run };
}

/**
 * The LinkedIn pipeline: the newest `date:` among the posted files, each a name ending in `.md` in
 * any case, as the LinkedIn view and Mark posted read the suffix. A file whose name starts with
 * the hub's idea prefix `idea` (`linkedin_idea_prefix`, empty for none) is an unposted idea and
 * carries no date that counts. The folder lives in the website repository beside the hub, which is
 * a separate checkout, so an absent folder is the ordinary case.
 */
function linkedin(
    dir: string,
    idea: string,
    catalog: TextCatalog,
    findings: Finding[]
): Feeds['linkedin'] {
    let names: string[];
    try {
        if (!statSync(dir).isDirectory()) return null;
        names = readdirSync(dir);
    } catch {
        return null;
    }
    const dates: string[] = [];
    for (const name of names.sort()) {
        if (!/\.md$/i.test(name) || (idea !== '' && name.startsWith(idea))) continue;
        let text: string;
        try {
            text = readFileSync(join(dir, name), 'utf8');
        } catch (error) {
            findings.push({
                file: join(dir, name),
                key: '',
                message: findingText(catalog, 'findings.feeds.cannot_read', errorLine(error))
            });
            continue;
        }
        const found = FRONT_DATE.exec(text);
        if (found !== null) dates.push(found[1]);
    }
    const newest = dates.sort().at(-1);
    return { lastPost: newest ?? null };
}

/** What a YAML feed that cannot be read reports: the missing file's finding when it is named. */
function missing(catalog: TextCatalog, named: boolean): () => string | null {
    return () => (named ? findingText(catalog, 'findings.registries.file_missing') : null);
}

/**
 * Read the three feed sources. Each is independent: a broken radar costs the radar line and nothing
 * else. Nothing here throws and no value is repaired. `unnamed` are the YAML feeds the hub's
 * settings file does not name, whose missing file is no finding; absent, both are named. A YAML
 * feed whose file is the empty text, one the hub's `feed_registries` leaves out, is not read and
 * is no finding, and neither is the LinkedIn folder of a hub whose `linkedin_dir` is empty. The
 * scout's run word and the LinkedIn idea prefix are the hub's `layout`.
 */
export function readFeeds(
    hub: string,
    files: FeedFiles,
    catalog: TextCatalog,
    merged: Record<string, unknown>,
    layout: HubLayout,
    unnamed: readonly FeedKind[] = []
): { feeds: RawFeeds; findings: Finding[] } {
    const findings: Finding[] = [];
    const named = !unnamed.includes('leads');
    const word = layout.leadsRunWord;
    const both =
        files.leads === ''
            ? { leads: null, scout: null }
            : leads(join(hub, files.leads), catalog, merged, word, findings, named);
    const radarNamed = !unnamed.includes('radar');
    const feeds: RawFeeds = {
        leads: both.leads,
        radar:
            files.radar === ''
                ? null
                : radar(join(hub, files.radar), catalog, findings, radarNamed),
        scout: both.scout,
        linkedin:
            files.linkedin === ''
                ? null
                : linkedin(join(hub, files.linkedin), layout.linkedinIdeaPrefix, catalog, findings)
    };
    return { feeds, findings };
}
